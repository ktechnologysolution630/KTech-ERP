/** Keyword list flattened and sorted longest first, so the most specific word is tried first */
const KEYWORDS: { word: string; groupCode: string }[] = Object.entries(GROUP_KEYWORDS)
  .flatMap(([groupCode, words]) => words.map((w) => ({ word: normalizeSearch(w), groupCode })))
  .sort((a, b) => b.word.length - a.word.length);

export interface DetectedItemType {
  category: StockCategory;
  /** Group name under the category ('' when only the category is known) */
  group: string;
  /** How it was found: an item already in the register, or a word in the name */
  source: 'register' | 'keyword';
  /** The register item or word that decided it */
  matched: string;
}

/** Item as the register holds it */
export interface RegisterItem {
  code: string;
  name: string;
  category?: string | null;
}

/** Latin words need a boundary so "lan" does not fire inside "plan"; Thai has no spaces between words */
function containsWord(hay: string, word: string): boolean {
  // A very short Thai word ("สี") only counts at the start of a word, not inside "เสียง"
  if (!/^[a-z0-9]/.test(word)) return word.length > 2 ? hay.includes(word) : hay.startsWith(word) || hay.includes(` ${word}`);
  const at = hay.indexOf(word);
  if (at < 0) return false;
  let i = at;
  while (i >= 0) {
    const before = i === 0 ? '' : hay[i - 1];
    const after = hay[i + word.length] ?? '';
    if (!/[a-z0-9]/.test(before) && !/[a-z]/.test(after)) return true;
    i = hay.indexOf(word, i + 1);
  }
  return false;
}

/** Category and group of a typed name from its words alone */
export function detectByKeyword(text: string): DetectedItemType | null {
  const hay = normalizeSearch(text);
  if (hay.length < 2) return null;
  for (const k of KEYWORDS) {
    if (!containsWord(hay, k.word)) continue;
    const g = ITEM_GROUPS.find((x) => x.code === k.groupCode);
    if (g) return { category: g.category, group: g.name, source: 'keyword', matched: k.word };
  }
  return null;
}

/**
 * Category and group for what someone types as an item name. The register comes first: an item
 * of the same name, else one whose name contains the text (or the other way round), says where
 * it belongs. Otherwise words in the name decide (สังกะสี → งานสถาปัตยกรรม › งานหลังคา).
 * Null when nothing points anywhere.
 */
export function detectItemType(text: string, register: readonly RegisterItem[] = []): DetectedItemType | null {
  const q = normalizeSearch(text);
  if (q.length < 2) return null;
  const byWord = detectByKeyword(q);

  const placed = (item: RegisterItem) => {
    const c = classifyItem(item);
    return c.category ? { category: c.category, group: c.group, item } : null;
  };
  const exact = register.find((i) => normalizeSearch(i.name) === q || normalizeSearch(i.code) === q);
  const near =
    exact ??
    (q.length >= 3
      ? register.find((i) => {
          const n = normalizeSearch(i.name);
          return n.length >= 3 && (n.includes(q) || q.includes(n)) && placed(i);
        })
      : undefined);
  const fromRegister = near ? placed(near) : null;

  if (fromRegister) {
    // The register knows the category; a keyword under the same category fills a missing group
    const group = fromRegister.group || (byWord && byWord.category === fromRegister.category ? byWord.group : '');
    return { category: fromRegister.category, group, source: 'register', matched: near!.name };
  }
  return byWord;
}
